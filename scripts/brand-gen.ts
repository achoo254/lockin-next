/**
 * `pnpm brand:gen`: everything the platforms show of the brand, derived from the AI-drawn master icon
 * (brand/app-icon-master-1024.png) and brand.config.json, with the Chromium of @playwright/test:
 *
 * - brand/app-icon.svg and app-icon-maskable.svg: the master embedded as WebP, the sources @achoo254/brand draws
 *   from. The master is full-bleed (its lime runs to the edges) with the padlock sticker inside the central safe
 *   circle, so the maskable icon is the same picture;
 * - brand/generated/: web manifest, PNG icons (192, 512, maskable, Apple touch) and favicon.ico (writeBrandFiles);
 * - apps/web/public/brand-mark-96.webp: the header mark;
 * - apps/web/public/og-image.png: the 1200 × 630 link preview in the app's sticker look: on lime, the icon as a
 *   black-outlined sticker beside the name in black, the value line on a white sticker and the host, drawn here as
 *   text in the app's own fonts and the colours of apps/web/src/ui/tokens.css.
 *
 * Run after changing the master, the tokens or the brand, then commit the files.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { chromiumRenderer, writeBrandFiles } from '@achoo254/brand/build';
import { primaryOrigin } from '@achoo254/brand/hosts';
import { type Page, chromium } from '@playwright/test';
import { vi as messages } from '../apps/web/src/i18n/messages';
import { BRAND_GENERATED_DIR, BRAND_ROOT, MANIFEST_OPTIONS, OG_IMAGE, loadLockinBrand } from '../apps/web/vite-brand';
import { parseTokens } from './token-contrast';

const MASTER = new URL('brand/app-icon-master-1024.png', BRAND_ROOT);
const TOKENS = new URL('apps/web/src/ui/tokens.css', BRAND_ROOT);
const PUBLIC_DIR = new URL('apps/web/public/', BRAND_ROOT);
const ICON_LICENCE = 'AI-generated (OpenAI gpt-image-2) for the hoandat ecosystem; owned by hoandat, all rights reserved (not CC0)';

/** The master scaled to `size` px and encoded by the browser, as a data URL. */
async function encodeMaster(page: Page, masterDataUrl: string, size: number, type: 'image/webp' | 'image/png'): Promise<string> {
  return page.evaluate(
    async ({ src, size, type }) => {
      const image = new Image();
      image.src = src;
      await image.decode();
      const canvas = document.createElement('canvas');
      canvas.width = size;
      canvas.height = size;
      const context = canvas.getContext('2d');
      if (!context) throw new Error('no 2d context');
      context.imageSmoothingQuality = 'high';
      context.drawImage(image, 0, 0, size, size);
      return canvas.toDataURL(type, 0.92);
    },
    { src: masterDataUrl, size, type },
  );
}

function dataUrlBytes(dataUrl: string, type: string): Buffer {
  const prefix = `data:${type};base64,`;
  if (!dataUrl.startsWith(prefix)) throw new Error(`brand:gen: Chromium did not encode ${type}`);
  return Buffer.from(dataUrl.slice(prefix.length), 'base64');
}

function iconSvg(webpDataUrl: string, appName: string, maskable: boolean): string {
  const what = maskable ? `Maskable ${appName} app icon` : `${appName} app icon`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><!-- ${what}: ${ICON_LICENCE}. Generated by pnpm brand:gen from brand/app-icon-master-1024.png. --><image width="1024" height="1024" href="${webpDataUrl}"/></svg>\n`;
}

const webRequire = createRequire(new URL('apps/web/package.json', BRAND_ROOT));

/** A @fontsource weight stylesheet with its WOFF2 files inlined (WOFF fallbacks dropped), so the page renders offline. */
function inlinedFontCss(stylesheet: string): string {
  const file = webRequire.resolve(stylesheet);
  return readFileSync(file, 'utf8').replace(/url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\)(, url\([^)]+\) format\('woff'\))?/g, (_match, name: string) => {
    const bytes = readFileSync(new URL(`files/${name}`, pathToFileURL(file)));
    return `url(data:font/woff2;base64,${bytes.toString('base64')}) format('woff2')`;
  });
}

interface OgColours {
  lime: string;
  ink: string;
  paper: string;
}

function ogColours(): OgColours {
  const tokens = parseTokens(readFileSync(TOKENS, 'utf8'));
  const v = (name: string): string => {
    const found = tokens.get(name);
    if (found === undefined) throw new Error(`brand:gen: tokens.css does not define ${name}`);
    return found;
  };
  return { lime: v('--c-lock'), ink: v('--c-text'), paper: v('--c-surface') };
}

function ogHtml(iconDataUrl: string, appName: string, line: string, host: string, c: OgColours): string {
  return `<!doctype html><html lang="vi"><head><style>
${inlinedFontCss('@fontsource/be-vietnam-pro/700.css')}
${inlinedFontCss('@fontsource/bricolage-grotesque/800.css')}
</style></head><body style="margin:0">
<div style="position:relative;width:${OG_IMAGE.width}px;height:${OG_IMAGE.height}px;overflow:hidden;color:${c.ink};font-family:'Be Vietnam Pro',sans-serif;background:${c.lime}">
<div style="position:absolute;top:0;bottom:0;left:88px;right:88px;display:flex;align-items:center;gap:64px">
<img src="${iconDataUrl}" width="330" height="330" alt="" style="flex:none;border-radius:72px;border:6px solid ${c.ink};box-shadow:14px 14px 0 ${c.ink}">
<div style="display:flex;flex-direction:column;align-items:flex-start;gap:26px">
<div style="font-family:'Bricolage Grotesque',sans-serif;font-weight:800;font-size:132px;line-height:.9;letter-spacing:-0.04em">${appName}</div>
<div style="font-family:'Bricolage Grotesque',sans-serif;font-weight:800;font-size:44px;line-height:1.15;letter-spacing:-0.02em;padding:14px 26px;border-radius:20px;background:${c.paper};border:4px solid ${c.ink};box-shadow:8px 8px 0 ${c.ink};transform:rotate(-1.5deg)">${line}</div>
<div style="padding:10px 24px;border-radius:999px;background:${c.paper};border:3px solid ${c.ink};font-size:28px;font-weight:700">${host}</div>
</div></div></div></body></html>`;
}

async function main(): Promise<void> {
  const brand = loadLockinBrand();
  const masterDataUrl = `data:image/png;base64,${readFileSync(MASTER).toString('base64')}`;
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ deviceScaleFactor: 1 });
    const webp512 = await encodeMaster(page, masterDataUrl, 512, 'image/webp');
    // Fails here, not in a broken SVG, if this Chromium cannot encode WebP.
    dataUrlBytes(webp512, 'image/webp');
    writeFileSync(new URL(brand.icon, BRAND_ROOT), iconSvg(webp512, brand.appName, false));
    writeFileSync(new URL(brand.iconMaskable, BRAND_ROOT), iconSvg(webp512, brand.appName, true));
    writeFileSync(new URL('brand-mark-96.webp', PUBLIC_DIR), dataUrlBytes(await encodeMaster(page, masterDataUrl, 96, 'image/webp'), 'image/webp'));

    await page.setViewportSize({ width: OG_IMAGE.width, height: OG_IMAGE.height });
    await page.setContent(ogHtml(webp512, brand.appName, `${messages['home.titleStart']} ${messages['home.titleEm']}`, new URL(primaryOrigin(brand)).host, ogColours()));
    await page.locator('img').evaluateAll((images: HTMLImageElement[]) => Promise.all(images.map((img) => img.decode())));
    await page.evaluate(() => document.fonts.ready);
    writeFileSync(new URL(OG_IMAGE.path, PUBLIC_DIR), await page.screenshot({ clip: { x: 0, y: 0, width: OG_IMAGE.width, height: OG_IMAGE.height } }));
  } finally {
    await browser.close();
  }
  const written = await writeBrandFiles({
    brand,
    root: BRAND_ROOT,
    generatedDir: BRAND_GENERATED_DIR,
    manifests: MANIFEST_OPTIONS,
    indent: 2,
    renderer: chromiumRenderer(chromium),
  });
  console.log(`Wrote brand SVGs, header mark, og-image and ${written.length} files to brand/generated/: ${written.join(', ')}`);
}

main().catch((error: unknown) => {
  console.error('brand:gen failed:', error);
  process.exitCode = 1;
});
